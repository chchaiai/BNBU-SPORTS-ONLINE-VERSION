import fs from 'node:fs';
import assert from 'node:assert/strict';
import {chromium} from '../../.local/browser-test/node_modules/playwright-core/index.mjs';
const state=JSON.parse(fs.readFileSync(new URL('../../.local/v81-browser-state/state.json',import.meta.url)));
const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE??'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
let stage='LOGIN';
let diagnosticPage; const responses=[];
try{
  const page=await browser.newPage(); diagnosticPage=page;page.setDefaultTimeout(45000);
  page.on('response',response=>{const path=new URL(response.url()).pathname;if(path.startsWith('/api/v1/'))responses.push({path,status:response.status()});});
  await page.goto('http://localhost:3300/');
  await page.getByLabel('学校邮箱').fill(state.accounts.teacher.email);
  await page.locator('#login-password').fill(state.accounts.teacher.password);
  const catalogPromise=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/v1/class-sections'&&response.ok());
  await page.getByRole('button',{name:'登录',exact:true}).click();
  await page.getByRole('button',{name:/进入课程/}).first().waitFor();
  const catalog=(await (await catalogPromise).json()).data;
  const courseIndex=(Array.isArray(catalog)?catalog:catalog.items).findIndex(section=>section.id===state.fixture.teacherAActiveSectionId);
  assert.ok(courseIndex>=0);stage='NORMAL_GRADE';
  await page.getByRole('button',{name:'内部成绩册',exact:true}).click();
  await page.waitForLoadState('networkidle');
  await page.getByRole('combobox',{name:'当前课程',exact:true}).click();
  await page.getByRole('option').nth(courseIndex).click();
  const edit=page.getByRole('button',{name:/录入成绩|查看 \/ 修改成绩/}).first();
  await edit.click();
  await page.getByLabel('最终成绩').fill('1.5');
  await page.getByRole('button',{name:'保存成绩',exact:true}).click();
  await page.getByText('请填写 -2147483648 至 2147483647 之间的整数成绩。').waitFor();
  await page.getByLabel('最终成绩').fill('123');
  const saved=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/final-grades'));
  await page.getByRole('button',{name:'保存成绩',exact:true}).click();
  const savedResponse=await saved; assert.equal(savedResponse.status(),201);
  const draft=(await savedResponse.json()).data; assert.equal(draft.finalGrade,123);assert.equal(draft.published,false);
  await page.getByRole('button',{name:/发布成绩（/}).click();
  const published=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/final-grades'));
  await page.getByRole('button',{name:'确认发布',exact:true}).click();
  const pubResponse=await published;assert.equal(pubResponse.status(),201);
  const revision=(await pubResponse.json()).data;assert.equal(revision.finalGrade,123);assert.equal(revision.published,true);
  assert.equal(revision.version,draft.version+1);
  await page.reload();await page.waitForLoadState('networkidle');
  await page.getByRole('button',{name:'内部成绩册',exact:true}).click();
  await page.getByRole('combobox',{name:'当前课程',exact:true}).click();
  await page.getByRole('option').nth(courseIndex).click();
  await page.getByRole('button',{name:'查看 / 修改成绩',exact:true}).first().click();
  assert.equal(await page.getByLabel('最终成绩').inputValue(),'123');
  assert.ok(!responses.some(r=>r.path.includes('/student-scores')));
  console.log(JSON.stringify({check:'TEACHER_FINAL_GRADE_SAVE_PUBLISH_RELOAD',result:'PASS',draftVersion:draft.version,publishedVersion:revision.version,integerOutside100:123}));
}catch(error){console.error(JSON.stringify({check:'TEACHER_NAVIGATION',result:'FAIL',stage,type:error.name,message:error.message.slice(0,700),enterCourseButtons:diagnosticPage?await diagnosticPage.getByRole('button',{name:/进入课程/}).count():0,failedRequests:responses.filter(item=>item.status>=400)}));process.exitCode=1;}
finally{await browser.close();}
