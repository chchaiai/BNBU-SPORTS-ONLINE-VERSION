import fs from 'node:fs';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {chromium} from '../../.local/browser-test/node_modules/playwright-core/index.mjs';
const state=JSON.parse(fs.readFileSync(new URL('../../.local/v81-browser-state/state.json',import.meta.url)));
const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE??'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
let stage='LOGIN',page;const failures=[];
try{
  page=await browser.newPage();
  page.setDefaultTimeout(15000);
  page.on('response',response=>{const path=new URL(response.url()).pathname.replace(/(\/course-invites\/)[^/]+\.[^/]+/,'$1[redacted]');if(path.startsWith('/api/v1/')&&response.status()>=400)failures.push({path,status:response.status()});});
  await page.goto('http://localhost:3300/');
  await page.getByLabel('学校邮箱').fill(state.accounts.teacher.email);
  await page.locator('#login-password').fill(state.accounts.teacher.password);
  await page.getByRole('button',{name:'登录',exact:true}).click();
  stage='CREATE';
  await page.getByRole('button',{name:/新建课程/}).click();
  const name='Synthetic Publish '+randomUUID();
  await page.getByPlaceholder('如 大学体育（一）').fill(name);
  const createdResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/v1/teacher/courses'&&response.request().method()==='POST');
  await page.getByRole('button',{name:'创建课程',exact:true}).click();
  const created=await createdResponse;
  assert.equal(created.status(),201);
  const createdBody=await created.json();
  assert.match(createdBody.data.id,/^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
  const replay=await page.request.post(created.url(),{headers:await created.request().allHeaders(),data:created.request().postData()});
  assert.equal(replay.status(),201);
  assert.deepEqual((await replay.json()).data,createdBody.data);
  console.log(JSON.stringify({check:'TEACHER_CREATE_UUID7_IDEMPOTENT_REPLAY',result:'PASS'}));
  const card=page.locator('.teacher-course-card').filter({hasText:name});
  await card.waitFor();
  stage='CONFIGURE';
  await card.getByRole('button',{name:/进入课程/}).click();
  const template=page.locator('#course-published-template');
  await page.waitForFunction(()=>document.querySelector('#course-published-template')?.options.length>1);
  await template.selectOption({index:1});
  await page.getByRole('combobox',{name:'打卡状态',exact:true}).click();
  await page.getByRole('option',{name:'允许打卡',exact:true}).click();
  const dialog=page.getByRole('dialog'),dates=dialog.locator('input[type=date]'),times=dialog.locator('input[type=time]');
  for(const [i,value]of ['2027-01-23','2026-09-09','2027-01-30'].entries())await dates.nth(i).fill(value);
  await times.nth(0).fill('00:00');await times.nth(1).fill('23:59');
  stage='VALIDATION_RECOVERY';
  await dates.nth(0).fill('2026-09-10');await dates.nth(2).fill('2026-09-17');
  const rejectedResponse=page.waitForResponse(response=>new URL(response.url()).pathname.endsWith('/v81-rules')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'保存设置',exact:true}).click();
  assert.equal((await rejectedResponse).status(),422);
  const sectionUrl=new URL(`/api/v1/class-sections/${createdBody.data.id}`,page.url()).href;
  const authHeaders={authorization:(await created.request().allHeaders()).authorization};
  const rejectedSection=await page.request.get(sectionUrl,{headers:authHeaders});
  assert.equal(rejectedSection.status(),200);
  assert.equal((await rejectedSection.json()).data.isEnrollmentOpen,false);
  await page.getByRole('alert').first().waitFor();
  await dates.nth(0).fill('2027-01-23');await dates.nth(2).fill('2027-01-30');
  stage='PUBLISH';
  const publishedResponse=page.waitForResponse(response=>new URL(response.url()).pathname.endsWith('/v81-rules')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'保存设置',exact:true}).click();
  const published=await publishedResponse;
  assert.equal(published.status(),201);
  const openedSection=await page.request.get(sectionUrl,{headers:authHeaders});
  assert.equal((await openedSection.json()).data.isEnrollmentOpen,true);
  await dialog.waitFor({state:'hidden'});
  await page.reload();
  await card.getByRole('button',{name:/进入课程/}).click();
  await page.getByText(/已发布：门槛/).waitFor();
  assert.equal(await template.isDisabled(),true);
  const locked=await page.request.post(published.url(),{headers:{...await published.request().allHeaders(),'idempotency-key':randomUUID()},data:published.request().postData()});
  assert.equal(locked.status(),409);
  console.log(JSON.stringify({check:'PUBLISHED_COURSE_SERVER_REJECTS_RULE_REWRITE',result:'PASS'}));
  console.log(JSON.stringify({check:'COURSE_CAPACITY_REJECTION_CORRECT_AND_REPUBLISH',result:'PASS'}));
  console.log(JSON.stringify({check:'TEACHER_BROWSER_CREATE_CONFIGURE_PUBLISH_RELOAD_LOCK',result:'PASS'}));
  stage='INVITE';
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  await card.getByRole('button',{name:'邀请二维码',exact:true}).click();
  const inviteResponse=page.waitForResponse(response=>new URL(response.url()).pathname.endsWith('/course-invites')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'生成新邀请码',exact:true}).click();
  const invitation=await inviteResponse;assert.equal(invitation.status(),201);
  const inviteToken=(await invitation.json()).data.inviteToken;
  const inviteUrl=new URL(`/api/v1/course-invites/${encodeURIComponent(inviteToken)}`,page.url()).href;
  assert.equal((await page.request.get(`${inviteUrl}/preview`)).status(),200);
  const capabilityResponse=await page.request.post(`${inviteUrl}/join-capabilities`,{headers:{'idempotency-key':randomUUID()},data:{fullName:'Synthetic Pending Join',studentNumber:'S'+randomUUID().replaceAll('-','').slice(0,29),gender:'MALE',gradeYear:2026}});
  assert.equal(capabilityResponse.status(),201);
  const capability=(await capabilityResponse.json()).data.joinCapability;
  await page.getByRole('button',{name:'撤销邀请码',exact:true}).waitFor();
  console.log(JSON.stringify({check:'PUBLISHED_COURSE_BROWSER_INVITE',result:'PASS'}));
  stage='REVOKE';
  await page.getByRole('button',{name:'撤销邀请码',exact:true}).click();
  const revokedResponse=page.waitForResponse(response=>new URL(response.url()).pathname.endsWith('/course-invites/revocations')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'确认撤销',exact:true}).click();
  const revoked=await revokedResponse;assert.equal(revoked.status(),201);
  const revokeReplay=await page.request.post(revoked.url(),{headers:await revoked.request().allHeaders(),data:revoked.request().postData()});
  assert.equal(revokeReplay.status(),201);assert.deepEqual((await revokeReplay.json()).data,(await revoked.json()).data);
  assert.equal((await page.request.get(`${inviteUrl}/preview`)).status(),410);
  const pendingJoin=await page.request.post(`${inviteUrl}/join`,{headers:{'idempotency-key':randomUUID(),'x-join-capability':capability}});
  assert.equal(pendingJoin.status(),401);
  await dialog.waitFor({state:'hidden'});
  await card.getByRole('button',{name:'邀请二维码',exact:true}).click();
  await page.getByRole('button',{name:'生成新邀请码',exact:true}).waitFor();
  console.log(JSON.stringify({check:'INVITE_REVOKED_REPLAY_PREVIEW_AND_PENDING_JOIN_DENIED',result:'PASS'}));
}catch(error){console.error(JSON.stringify({check:'TEACHER_BROWSER_CREATE_CONFIGURE_PUBLISH_RELOAD_LOCK',result:'FAIL',stage,type:error.name,failures,alerts:await page.getByRole('alert').allTextContents()}));
  if((stage==='PUBLISH'||stage==='CREATE')&&await page.getByRole('dialog').count())console.error(JSON.stringify({dialogText:(await page.getByRole('dialog').innerText()).slice(-2500)}));process.exitCode=1;}
finally{await browser.close();}
