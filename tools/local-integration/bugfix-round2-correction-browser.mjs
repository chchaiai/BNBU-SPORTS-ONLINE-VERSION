import fs from 'node:fs';
import assert from 'node:assert/strict';
import {chromium} from '../../.local/browser-test/node_modules/playwright-core/index.mjs';
const state=JSON.parse(fs.readFileSync('.local/v81-browser-state/state.json','utf8'));
assert.equal(state.database,'v81_browser_test');
const {recordId}=JSON.parse(fs.readFileSync('.local/v81-browser-state/camera-submission-round2-submit-retry.json','utf8'));
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
let stage='LOGIN',page;
try{
 page=await browser.newPage();page.setDefaultTimeout(120000);
 await page.goto('http://localhost:3300/');
 await page.locator('#login-account').fill(state.accounts.teacher.email);
 await page.locator('#login-password').fill(state.accounts.teacher.password);
 const loggedIn=page.waitForResponse(r=>new URL(r.url()).pathname.endsWith('/auth/password-login'));
 await page.getByRole('button',{name:'登录',exact:true}).click();
 const token=(await(await loggedIn).json()).data.accessToken;
 const read=async path=>{const response=await page.request.get('http://127.0.0.1:3199/api/v1'+path,{headers:{authorization:`Bearer ${token}`}});assert.equal(response.status(),200);return(await response.json()).data;};
 const detail=await read(`/exercise-records/${recordId}`),student=await read(`/students/${detail.studentId}`);
 const before=await read(`/exercise-records/${recordId}/workflow`);assert.equal(before.stage,'VALID');
 await page.getByRole('button',{name:/新建课程/}).waitFor();
 stage='QUEUE';
 await page.getByRole('button',{name:'打卡审核',exact:true}).click();
 await page.getByRole('tab',{name:/全部记录/}).click();
 await page.getByRole('row').filter({hasText:student.fullName}).getByRole('button',{name:/查看记录/}).click();
 const record=page.locator(`#checkin-record-${recordId}`);
 stage='CORRECT_INVALID';
 await record.getByRole('radio',{name:'无效',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByRole('radio',{name:/材料不清晰/}).click();
 await dialog.getByRole('button',{name:'确认标记无效',exact:true}).click();
 await dialog.getByText('请填写纠正说明。',{exact:true}).waitFor();
 const notes=dialog.locator('textarea');
 await notes.nth(0).fill('合成验收：依据已有材料纠正有效结论');
 await notes.nth(1).fill('合成验收公开补充说明');
 const corrected=page.waitForResponse(r=>new URL(r.url()).pathname===`/api/v1/exercise-records/${recordId}/corrections`&&r.request().method()==='POST');
 await dialog.getByRole('button',{name:'确认标记无效',exact:true}).click();
 const response=await corrected;assert.ok(response.ok());
 const invalid=await read(`/exercise-records/${recordId}/workflow`);
 assert.equal(invalid.stage,'INVALID');assert.equal(invalid.publicComment,'合成验收公开补充说明');assert.ok(invalid.version>before.version);
 await dialog.waitFor({state:'hidden'});
 stage='CORRECT_VALID';
 await record.getByRole('radio',{name:'通过',exact:true}).click();
 await dialog.locator('textarea').fill('合成验收结束，依据既有事实恢复有效结论');
 const restored=page.waitForResponse(r=>new URL(r.url()).pathname===`/api/v1/exercise-records/${recordId}/corrections`&&r.request().method()==='POST');
 await dialog.getByRole('button',{name:'确认纠正为有效',exact:true}).click();assert.ok((await restored).ok());
 const final=await read(`/exercise-records/${recordId}/workflow`);assert.equal(final.stage,'VALID');assert.ok(final.version>invalid.version);
 console.log(JSON.stringify({check:'TEACHER_BROWSER_VALID_INVALID_VALID_CORRECTION_REASON_PUBLIC_COMMENT',result:'PASS'}));
}catch(error){console.error(JSON.stringify({check:'TEACHER_BROWSER_CORRECTION',result:'FAIL',stage,message:error.message.slice(0,700),page:await page.locator('body').innerText()}));process.exitCode=1;}
finally{await browser.close();}
