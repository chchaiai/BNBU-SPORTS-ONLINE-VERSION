import fs from 'node:fs';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
const output='.local/semester-header-target.json';
assert.ok(!fs.existsSync(output));
const credentials=JSON.parse(fs.readFileSync('.local/semester-browser-credentials.json'));
const base='https://www.teacher.bnbusports.cn/api/v1';
const response=await fetch(base+'/auth/password-login',{method:'POST',headers:{'content-type':'application/json','idempotency-key':randomUUID()},body:JSON.stringify({account:credentials.email,password:credentials.password})});
assert.equal(response.status,200);
const token=(await response.json()).data.accessToken;
const headers={authorization:`Bearer ${token}`,'content-type':'application/json'};
const me=await fetch(base+'/me',{headers});assert.equal(me.status,200);
assert.equal((await me.json()).data.user.organizationId,'01a09918-10d0-75ae-93a0-a4bf948d2495');
const existing=await fetch(base+'/admin/semesters?limit=100',{headers});
assert.equal(existing.status,200);
const page=(await existing.json()).data;
assert.equal(page.nextCursor,null);
assert.ok(!page.items.some(row=>row.displayName==='Synthetic header synchronization acceptance'),'Target already exists; inspect it instead of creating again');
const create=await fetch(base+'/admin/semesters',{method:'POST',headers:{...headers,'idempotency-key':randomUUID()},body:JSON.stringify({academicYear:'2027-2028',termCode:'FIRST',displayName:'Synthetic header synchronization acceptance',startDate:'2026-09-13',endDate:'2027-12-31'})});
assert.equal(create.status,201);
const target=(await create.json()).data;
fs.writeFileSync(output,JSON.stringify(target,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({id:target.id,displayName:target.displayName,status:target.status,scope:'Synthetic organization only; browser switch target'}));
